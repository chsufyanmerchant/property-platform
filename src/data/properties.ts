/** Number of active mock listings in a given city — used by PopularCities. */
export function getListingCountForCity(city: string): number {
  return properties.filter((property) => property.location.city === city).length;
}

/** Number of active mock listings of a given type — used by PropertyCategories. */
export function getListingCountForType(type: Property["type"]): number {
  return properties.filter((property) => property.type === type).length;
}

export function getFeaturedProperties(): Property[] {
  return properties.filter((property) => property.isFeatured);
}

/**
 * Ranks every other listing by relevance to `current` and returns the top
 * matches — same type scores highest, then same city, then same purpose.
 * Ties keep their original dataset order (Array.sort is stable).
 */
export function getSimilarProperties(current: Property, limit = 4): Property[] {
  return properties
    .filter((property) => property.id !== current.id)
    .map((property) => {
      let score = 0;
      if (property.type === current.type) score += 3;
      if (property.location.city === current.location.city) score += 2;
      if (property.purpose === current.purpose) score += 1;
      return { property, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => entry.property);
}